-- Duffy Review : PostgreSQL schema
-- รันซ้ำได้ปลอดภัย (IF NOT EXISTS) เซิร์ฟเวอร์จะรันไฟล์นี้อัตโนมัติตอนเริ่มทำงาน ถ้ามี DATABASE_URL

-- เกมที่รีวิว
CREATE TABLE IF NOT EXISTS games (
  id           INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title        TEXT        NOT NULL,                              -- ชื่อเกม
  category     TEXT        NOT NULL,                              -- หมวดหมู่ (แอคชัน, RPG, ผจญภัย, แข่งรถ, จำลอง, ต่อสู้)
  age          INT         NOT NULL CHECK (age IN (3, 7, 12, 16, 18)),  -- เรตอายุ
  score        NUMERIC(3,1) NOT NULL CHECK (score BETWEEN 0 AND 10),    -- คะแนนรีวิว
  base_views   INT         NOT NULL DEFAULT 0,                    -- ยอดวิวตั้งต้น (ยอดจริงอยู่ในตาราง views)
  release_date DATE        NOT NULL DEFAULT CURRENT_DATE,         -- วันที่ลงรีวิว
  description  TEXT        NOT NULL DEFAULT '',                   -- คำอธิบายสั้นบนการ์ด
  review       TEXT        NOT NULL DEFAULT '',                   -- เนื้อรีวิวเต็ม (เว้นย่อหน้าด้วยบรรทัดว่าง)
  pros         TEXT[]      NOT NULL DEFAULT '{}',                 -- จุดเด่น
  cons         TEXT[]      NOT NULL DEFAULT '{}',                 -- จุดด้อย
  platforms    TEXT        NOT NULL DEFAULT '',                   -- เช่น 'PS5 · PC'
  image        TEXT        NOT NULL DEFAULT '',                   -- เช่น 'images/dragon.jpg' หรือ 'https://...'
  hue          INT         NOT NULL DEFAULT 200,                  -- สีพื้นหลังสำรองเมื่อไม่มีรูป (0-360)
  created_at   TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS games_category_idx ON games (category);
CREATE INDEX IF NOT EXISTS games_age_idx      ON games (age);

-- ยอดเข้าชมจริง (บวกเพิ่มทุกครั้งที่มีคนเปิดรีวิว)
CREATE TABLE IF NOT EXISTS views (
  game_id INT PRIMARY KEY REFERENCES games (id) ON DELETE CASCADE,
  count   INT NOT NULL DEFAULT 0
);

-- ความคิดเห็นและคะแนนจากผู้อ่าน
CREATE TABLE IF NOT EXISTS comments (
  id      TEXT PRIMARY KEY,
  game_id INT  NOT NULL REFERENCES games (id) ON DELETE CASCADE,
  name    TEXT NOT NULL,
  text    TEXT NOT NULL,
  rating  INT  CHECK (rating BETWEEN 1 AND 5),
  date    TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS comments_game_idx ON comments (game_id, date DESC);

-- ดาวที่ผู้อ่านให้ (1 เบราว์เซอร์ต่อ 1 เกม เปลี่ยนดาวได้) ใช้คำนวณคะแนนรวม
CREATE TABLE IF NOT EXISTS ratings (
  game_id    INT  NOT NULL REFERENCES games (id) ON DELETE CASCADE,
  voter      TEXT NOT NULL,
  stars      INT  NOT NULL CHECK (stars BETWEEN 1 AND 5),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  PRIMARY KEY (game_id, voter)
);
